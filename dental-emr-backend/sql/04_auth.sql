USE dental_emr;
DROP TABLE IF EXISTS USER_ACCOUNT;
CREATE TABLE USER_ACCOUNT (
    UserID        INT AUTO_INCREMENT PRIMARY KEY,
    Username      VARCHAR(100) NOT NULL UNIQUE,
    PasswordHash  VARCHAR(200) NOT NULL,
    Role          VARCHAR(20)  NOT NULL,
    DoctorID      INT NULL,
    PatientID     INT NULL,
    EmployeeID    INT NULL,
    IsActive      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_user_role CHECK (Role IN ('RECEPTION','DOCTOR','PATIENT','ADMIN')),
    CONSTRAINT fk_user_doctor   FOREIGN KEY (DoctorID)   REFERENCES DOCTOR(DoctorID)     ON DELETE CASCADE,
    CONSTRAINT fk_user_patient  FOREIGN KEY (PatientID)  REFERENCES PATIENT(PatientID)   ON DELETE CASCADE,
    CONSTRAINT fk_user_employee FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID) ON DELETE CASCADE
) ENGINE=InnoDB;